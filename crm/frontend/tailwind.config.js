/**
 * Оформление CRM — деловой минимализм.
 *
 * Прежняя тема была построена вокруг одного голубого: он был и цветом
 * действий, и фоном страницы, и цветом подписей, и заливкой сайдбара.
 * Экран получался «нарядным» — по нему было трудно понять, где данные,
 * а где украшение.
 *
 * Теперь ролей три и они не смешиваются:
 *   ink   — графитовая шкала: текст, рамки, фоны. Нейтральная, чуть
 *           холодная, без синевы в светлых тонах.
 *   brand — синий #0078C9 (цвет логотипа). Только действия и выделение
 *           текущего: кнопка, ссылка, активный пункт меню, выбранный день.
 *   служебные красный/янтарный/зелёный — только состояния.
 *
 * Имя navy сохранено как псевдоним ink: на него завязаны сотни классов по
 * всему коду, и переименование их всех дало бы огромную небезопасную
 * правку без единого выигрыша.
 */

