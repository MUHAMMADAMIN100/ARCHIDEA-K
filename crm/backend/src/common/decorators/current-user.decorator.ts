import { createParamDecorator, ExecutionContext } from '@nestjs/common';
import { Role } from '@prisma/client';

export interface AuthUser {
  id: string;
  login: string;
  role: Role;
  fullName: string;
  /** расширенный доступ: видит данные как директор, но без финансов */
  canManageOps: boolean;
  /** полный доступ к модулю задач: все задачи компании, а не только свои (ТЗ 1.2) */
  canManageTasks: boolean;
  canSeeTrash: boolean;
  /** персональный запрет на финансы — сильнее роли (см. permissions.ts) */
  noFinance: boolean;
  /** Персональный доступ к платёжным ведомостям — сильнее запрета на финансы */
  canSeeReports?: boolean;
  /** Владелец компании: единственный, кто удаляет сотрудников */
  isOwner: boolean;
}

/** Видит ли пользователь данные всей компании (руководитель, управляющий или ops-менеджер) */
export function seesAll(user: AuthUser): boolean {
  return (
    user.role === Role.DIRECTOR ||
    user.role === Role.SUPERVISOR ||
    user.canManageOps === true
  );
}

/**
 * Клиентская база компании — общая для всех сотрудников (решение владельца).
 *
 * Заказы, клиенты и всё, что к ним привязано: карточки, оплаты, чек-листы,
 * коммерческие предложения. Любой сотрудник открывает любой заказ, правит его,
 * заводит новый, двигает по воронке, вносит оплату и может передать
 * ответственного коллеге. Раньше каждый видел только своих клиентов, и стоило
 * человеку заболеть или уйти в отпуск — его сделки замирали: коллега их просто
 * не находил, а клиент звонил и не получал ответа.
 *
 * Это НЕ то же самое, что `seesAll` выше, и разделение здесь намеренное:
 *  - `seesWholeBase` — клиентская база: чьи заказы и клиенты доступны в работе;
 *  - `seesAll` — сводные данные компании: аналитика по менеджерам, общая лента
 *    журнала изменений, чужие профили. Там область осталась у руководства.
 *
 * Личные списки под это правило тоже не попадают: задачи и напоминания
 * остаются своими у каждого — это ежедневник сотрудника, а не база компании.
 *
 * Аргумент сохранён, хотя ответ сейчас одинаков для всех: он помечает каждое
 * место, где решается область данных. Понадобится вернуть ограничение —
 * правка будет в одной этой функции, а не в трёх десятках запросов.
 */
export function seesWholeBase(_user: AuthUser): boolean {
  return true;
}

/** Достаёт текущего пользователя (из JWT) в параметр метода */
export const CurrentUser = createParamDecorator(
  (data: keyof AuthUser | undefined, ctx: ExecutionContext) => {
    const request = ctx.switchToHttp().getRequest();
    const user: AuthUser = request.user;
    return data ? user?.[data] : user;
  },
);
