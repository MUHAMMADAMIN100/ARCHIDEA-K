import {
  PLACEHOLDER_LABELS,
  renderPlaceholders,
  renderProposalBody,
} from './template-render';

/**
 * Подстановки в шаблоне КП пишутся по-русски: «{{Имя клиента}}» вместо
 * «{{client}}» — иначе сотрудник, открывший шаблон впервые, не понимает,
 * что это за скобки. Английские названия остались в части шаблонов и
 * обязаны работать по-прежнему.
 */
const VALUES = {
  client: 'Курбонали',
  phone: '+992 10 222 20 02',
  address: 'Рудаки 21',
  total: '3840',
  manager: 'Аниса Мукими',
  items: '• Генеральная уборка',
};

describe('Подстановки в шаблоне КП', () => {
  it('понимает русское название', () => {
    expect(renderPlaceholders('Клиент: {{Имя клиента}}', VALUES)).toBe(
      'Клиент: Курбонали',
    );
  });

  it('понимает старое английское название — шаблоны не сломались', () => {
    expect(renderPlaceholders('Клиент: {{client}}', VALUES)).toBe(
      'Клиент: Курбонали',
    );
  });

  it('не придирается к регистру и лишним пробелам', () => {
    expect(renderPlaceholders('{{  имя КЛИЕНТА  }}', VALUES)).toBe('Курбонали');
  });

  it('понимает привычные слова: «Клиент», «Итого», «Адрес»', () => {
    expect(renderPlaceholders('{{Клиент}} · {{Итого}} · {{Адрес}}', VALUES)).toBe(
      'Курбонали · 3840 · Рудаки 21',
    );
  });

  it('название из двух слов не путается с соседним текстом', () => {
    expect(
      renderPlaceholders('Объект: {{Адрес объекта}}, вопросы — {{Менеджер}}', VALUES),
    ).toBe('Объект: Рудаки 21, вопросы — Аниса Мукими');
  });

  it('незнакомое в фигурных скобках остаётся как написано', () => {
    expect(renderPlaceholders('Клиент: {{Клинт}}!', VALUES)).toBe(
      'Клиент: {{Клинт}}!',
    );
  });

  // ── круглые скобки: основной вид метки (решение владельца) ──

  it('понимает круглые скобки', () => {
    expect(renderPlaceholders('Клиент: (Имя клиента)', VALUES)).toBe(
      'Клиент: Курбонали',
    );
  });

  it('круглые и фигурные дают ОДИН И ТОТ ЖЕ текст', () => {
    expect(renderPlaceholders('(Итоговая сумма) сомони', VALUES)).toBe(
      renderPlaceholders('{{Итоговая сумма}} сомони', VALUES),
    );
  });

  it('обычный текст в круглых скобках НЕ пропадает у клиента', () => {
    const text = 'Уборка (по договорённости), санузел (2 шт.)';
    expect(renderPlaceholders(text, VALUES)).toBe(text);
  });

  it('метка и пояснение в одной строке живут вместе', () => {
    expect(
      renderPlaceholders('(Имя клиента) — скидка (по акции)', VALUES),
    ).toBe('Курбонали — скидка (по акции)');
  });

  it('круглые скобки не придираются к регистру и пробелам', () => {
    expect(renderPlaceholders('(  имя КЛИЕНТА  )', VALUES)).toBe('Курбонали');
  });

  it('незакрытая круглая скобка не съедает текст', () => {
    expect(renderPlaceholders('Цена ( и дальше текст', VALUES)).toBe(
      'Цена ( и дальше текст',
    );
  });

  it('нет значения — пусто, а не слово undefined', () => {
    expect(renderPlaceholders('Скидка: {{Скидка}}', VALUES)).toBe('Скидка: ');
  });

  it('на каждое поле есть русское название', () => {
    expect(Object.values(PLACEHOLDER_LABELS).every((v) => /[А-Яа-я]/.test(v))).toBe(
      true,
    );
  });

  it('русский и английский шаблоны дают ОДИН И ТОТ ЖЕ текст', () => {
    const ru = {
      intro: 'Здравствуйте, {{Имя клиента}}!',
      body: 'Объект: {{Адрес объекта}}\nИтого: {{Итоговая сумма}} сомони',
      conditions: 'Подготовил: {{Менеджер}}',
    };
    const en = {
      intro: 'Здравствуйте, {{client}}!',
      body: 'Объект: {{address}}\nИтого: {{total}} сомони',
      conditions: 'Подготовил: {{manager}}',
    };
    expect(renderProposalBody(ru, VALUES)).toBe(renderProposalBody(en, VALUES));
  });

  it('одинокая скобка не съедает остальной текст', () => {
    expect(renderPlaceholders('Цена {{ и дальше текст', VALUES)).toBe(
      'Цена {{ и дальше текст',
    );
  });
});
