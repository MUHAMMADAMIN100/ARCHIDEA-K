import { byWorkDayDesc, reportDay, SortableReport } from './report-sort';

/**
 * Список ведомостей — по дням работ, новые сверху (просьба владельца).
 * В строке списка первой стоит дата работ, и порядок должен с ней совпадать.
 */
describe('Порядок ведомостей по дням работ', () => {
  const д = (iso: string) => new Date(iso);
  const ведомость = (
    name: string,
    workDate: string | null,
    createdAt: string,
    orderCreatedAt?: string,
  ): SortableReport & { name: string } => ({
    name,
    workDate: workDate ? д(`${workDate}T00:00:00.000Z`) : null,
    createdAt: д(createdAt),
    order: orderCreatedAt ? { createdAt: д(orderCreatedAt) } : null,
  });
  const порядок = (rows: (SortableReport & { name: string })[]) =>
    [...rows].sort(byWorkDayDesc).map((r) => r.name);

  it('новые дни работ сверху — независимо от того, когда ведомость составили', () => {
    // так было на экране владельца: 28.09, 29.09, 27.09, … 19.09, 22.09
    const rows = [
      ведомость('Компрон', '2026-09-28', '2026-09-29T10:00:00Z', '2026-09-25T08:00:00Z'),
      ведомость('Зулайхо', '2026-09-29', '2026-09-29T09:00:00Z', '2026-09-26T08:00:00Z'),
      ведомость('Валерия', '2026-09-27', '2026-09-28T09:00:00Z', '2026-09-26T07:00:00Z'),
      ведомость('Умед', '2026-09-19', '2026-09-22T12:00:00Z', '2026-09-02T08:00:00Z'),
      ведомость('Абдуахад', '2026-09-22', '2026-09-22T11:00:00Z', '2026-09-21T08:00:00Z'),
    ];
    expect(порядок(rows)).toEqual(['Зулайхо', 'Компрон', 'Валерия', 'Абдуахад', 'Умед']);
  });

  it('в один день работ выше ведомость с более новым заказом', () => {
    const rows = [
      ведомость('Довуд', '2026-09-25', '2026-09-25T15:00:00Z', '2026-09-23T06:00:00Z'),
      ведомость('Умед', '2026-09-25', '2026-09-25T09:00:00Z', '2026-09-24T06:00:00Z'),
    ];
    expect(порядок(rows)).toEqual(['Умед', 'Довуд']);
  });

  it('заказ тоже совпал — выше составленная позже', () => {
    const rows = [
      ведомость('Первая', '2026-09-25', '2026-09-25T09:00:00Z', '2026-09-23T06:00:00Z'),
      ведомость('Вторая', '2026-09-25', '2026-09-25T15:00:00Z', '2026-09-23T06:00:00Z'),
    ];
    expect(порядок(rows)).toEqual(['Вторая', 'Первая']);
  });

  it('без даты работ ведомость встаёт по дню составления — по Душанбе', () => {
    // 24.09 в 20:30 UTC — это уже 25.09 в Душанбе: строка показывает 25.09
    const безДаты = ведомость('Без даты', null, '2026-09-24T20:30:00Z');
    expect(reportDay(безДаты)).toBe('2026-09-25');
    const rows = [
      ведомость('24-го', '2026-09-24', '2026-09-24T10:00:00Z'),
      безДаты,
      ведомость('26-го', '2026-09-26', '2026-09-26T10:00:00Z'),
    ];
    expect(порядок(rows)).toEqual(['26-го', 'Без даты', '24-го']);
  });

  it('дата работ — календарный день, без сдвига на часовой пояс', () => {
    expect(reportDay(ведомость('x', '2026-08-19', '2026-09-01T10:00:00Z'))).toBe('2026-08-19');
  });
});
