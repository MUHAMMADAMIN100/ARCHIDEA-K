import { ShiftGroupStatus } from '@prisma/client';
import { ShiftGroupsService } from './shift-groups.service';

/**
 * В каком дне многодневной уборки лежат разовые сотрудники.
 *
 * Разовому отдают сумму на руки один раз за всю работу, поэтому в учёте он
 * обязан быть ровно в одном выезде. Но первый день бывает уже закрыт, а
 * разовых вписали позже — тогда они лежат во втором, и трогать их нельзя:
 * закрытый выезд не правится, а «перенос в первый день» просто стёр бы
 * отданные деньги. Ровно так выглядит настоящий заказ на бою.
 */
describe('День разовых сотрудников', () => {
  // метод приватный, но правило денежное — проверяем его напрямую
  const день = (
    existing: { status: ShiftGroupStatus; members: { cleanerId: string | null }[] }[],
    дней: number,
  ) =>
    (
      ShiftGroupsService.prototype as unknown as {
        guestDayIndex: (e: typeof existing, d: number) => number;
      }
    ).guestDayIndex(existing, дней);

  const открыт = (гости = 0) => ({
    status: ShiftGroupStatus.PLANNED,
    members: Array.from({ length: гости }, () => ({ cleanerId: null })),
  });
  const закрыт = (гости = 0) => ({
    status: ShiftGroupStatus.CLOSED,
    members: Array.from({ length: гости }, () => ({ cleanerId: null })),
  });

  it('оба дня открыты — разовые в первом', () => {
    expect(день([открыт(), открыт()], 2)).toBe(0);
  });

  it('первый день закрыт без разовых — они остаются во втором', () => {
    expect(день([закрыт(), открыт(3)], 2)).toBe(1);
  });

  it('разовые уже посчитаны в закрытом дне — второй раз их не начисляем', () => {
    expect(день([закрыт(3), открыт()], 2)).toBe(-1);
  });

  it('все дни закрыты — ничего не трогаем', () => {
    expect(день([закрыт(), закрыт()], 2)).toBe(-1);
  });

  it('выездов ещё меньше, чем дней — разовые в первом новом', () => {
    expect(день([закрыт()], 3)).toBe(1);
  });

  it('уборка на один день — разовые в нём', () => {
    expect(день([открыт()], 1)).toBe(0);
  });
});
