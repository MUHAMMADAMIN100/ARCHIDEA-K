-- Телефоны любых стран: приводим базу к единому формату.
--
-- Раньше номер хранился как девять цифр без кода страны — система знала
-- только Таджикистан. Клиенты пишут с российских, американских и других
-- номеров, и рядом с ними местный номер без кода означал бы, что один и тот
-- же человек может завестись дважды, а поиск по номеру находил бы не всё.
--
-- Новый вид: код страны и номер подряд, только цифры — «992900000001».
-- Перенос трогает ТОЛЬКО те строки, которые выглядят как местный номер из
-- девяти цифр; всё остальное (пустое, уже с кодом, введённое вручную)
-- остаётся как есть.

-- ── Клиенты: основной номер ────────────────────────────────────────────────
-- Уникальность номера сохраняется: '992' дописывается всем одинаково, значит
-- совпасть два разных номера не могут.
UPDATE "Client"
SET "phone" = '992' || "phone"
WHERE "phone" ~ '^[0-9]{9}$';

-- ── Клиенты: запасные номера ───────────────────────────────────────────────
UPDATE "Client"
SET "extraPhones" = ARRAY(
  SELECT CASE WHEN p ~ '^[0-9]{9}$' THEN '992' || p ELSE p END
  FROM unnest("extraPhones") AS p
)
WHERE EXISTS (
  SELECT 1 FROM unnest("extraPhones") AS p WHERE p ~ '^[0-9]{9}$'
);

-- ── Сотрудники и клинеры ───────────────────────────────────────────────────
UPDATE "User"    SET "phone" = '992' || "phone" WHERE "phone" ~ '^[0-9]{9}$';
UPDATE "Cleaner" SET "phone" = '992' || "phone" WHERE "phone" ~ '^[0-9]{9}$';
