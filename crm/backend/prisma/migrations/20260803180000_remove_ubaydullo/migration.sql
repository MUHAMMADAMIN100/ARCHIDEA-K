-- Убайдулло убран из CRM (решение владельца).
--
-- Удаление «мягкое» — ровно то же, что делает кнопка «Удалить» в разделе
-- «Сотрудники»: запись остаётся в базе, но человек исчезает из списков, из
-- распределения заявок с сайта, из выбора ответственного и исполнителей, и
-- войти в систему больше не может. Жёсткое удаление здесь невозможно: на
-- сотрудника ссылаются его клиенты, заказы и записи журнала — они пропали
-- бы вместе с ним.
--
-- Клиенты и заказы, закреплённые за ним, НЕ трогаем: их видно в воронке
-- по фильтру менеджера, и владелец переназначит их сам. Молча переносить
-- чужую работу на другого человека система не должна.
UPDATE "User"
SET "deletedAt"    = COALESCE("deletedAt", NOW()),
    "deleteReason" = COALESCE("deleteReason", 'Убран из системы по решению владельца'),
    "isActive"     = false,
    "acceptsLeads" = false,
    -- гасим все выданные токены: открытые вкладки перестанут работать сразу
    "sessionEpoch" = "sessionEpoch" + 1
WHERE lower("login") IN ('ubaydullo', 'ubaydulo', 'убайдулло')
   OR "fullName" ILIKE 'убайдулло%';
