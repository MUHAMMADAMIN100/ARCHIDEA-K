-- Перенос прежних оплат в новый учёт (ТЗ 3.1, 3.2).
--
-- Отдельной миграцией, а не хвостом предыдущей, намеренно. Prisma выполняет
-- файл миграции одной транзакцией: упади перенос данных на неожиданной строке
-- — откатилась бы и уже созданная схема, а сервер при таком сбое не стартует
-- вовсе (scripts/db-deploy.js). Разделение оставляет схему закреплённой, и
-- повторять придётся только перенос.
--
-- Ещё одно следствие: таблица книги доходов не держит исключительную
-- блокировку от ALTER TABLE до конца всего переноса — раздел «Финансы»
-- остаётся доступным на чтение.

-- Если база занята длинной чужой транзакцией, лучше быстро и понятно упасть,
-- чем встать в очередь блокировок на неопределённое время.
SET LOCAL lock_timeout = '5s';

-- ── Перенос прежних оплат ──────────────────────────────────────────────────
-- У заказов, где уже стоит сумма оплаты, заводим один взнос на эту сумму.
-- Способ оставляем пустым: тогда его не спрашивали, и придумывать задним
-- числом «наличные» было бы враньём в отчётности.
INSERT INTO "OrderPayment" ("id", "orderId", "amount", "method", "note", "paidAt", "createdAt", "updatedAt")
SELECT
  'legacy_' || o."id",
  o."id",
  o."paidAmount",
  NULL,
  'Перенесено из прежнего учёта: способ оплаты тогда не фиксировался',
  COALESCE(o."closedAt", o."updatedAt"),
  NOW(),
  NOW()
FROM "Order" o
WHERE o."paidAmount" > 0
  -- Заказы в корзине переносим наравне с остальными. Пропусти мы их —
  -- восстановленный заказ остался бы без взносов, и первый же пересчёт
  -- (он считает оплату суммой взносов) обнулил бы подтверждённую оплату.
  AND NOT EXISTS (SELECT 1 FROM "OrderPayment" p WHERE p."orderId" = o."id");

-- ── Согласование с книгой доходов ──────────────────────────────────────────
-- С этого момента доход считается по взносам, а не по закрытию заказа. Чтобы
-- выручка не удвоилась и не пропала, прежние автозаписи «order:<id>:income»
-- переводим на перенесённый взнос: сумма и дата в отчётах остаются прежними,
-- меняется только то, к чему запись привязана.
UPDATE "FinanceEntry" f
SET "autoKey" = 'payment:legacy_' || f."orderId"
WHERE f."autoKey" = 'order:' || f."orderId" || ':income'
  AND EXISTS (SELECT 1 FROM "OrderPayment" p WHERE p."id" = 'legacy_' || f."orderId")
  AND NOT EXISTS (
    SELECT 1 FROM "FinanceEntry" x WHERE x."autoKey" = 'payment:legacy_' || f."orderId"
  );

-- Предоплаты по незакрытым заказам дохода в книге не имели вовсе: раньше он
-- записывался только при переходе в «Оплачено». Теперь такие деньги — обычный
-- взнос, и без этой строки они потерялись бы навсегда.
--
-- Условие «у заказа вообще нет дохода» шире, чем проверка по ключу, и это
-- принципиально: у записи, которую руководитель правил руками, ключ
-- обнуляется (finance.service: ручная правка отвязывает авто-запись от
-- источника). По ключу мы бы её не нашли, завели вторую строку на те же
-- деньги — и выручка по таким заказам удвоилась бы. Причём именно по тем,
-- где в учёт уже вмешивался человек.
INSERT INTO "FinanceEntry" ("id", "kind", "category", "amount", "date", "title", "source", "autoKey", "orderId", "clientId", "createdAt", "updatedAt")
SELECT
  'legacyfin_' || o."id",
  'INCOME',
  'ORDER_PAYMENT',
  p."amount",
  p."paidAt",
  'Оплата заказа — способ не указан',
  'AUTO',
  'payment:' || p."id",
  o."id",
  o."clientId",
  NOW(),
  NOW()
FROM "OrderPayment" p
JOIN "Order" o ON o."id" = p."orderId"
WHERE p."id" = 'legacy_' || o."id"
  AND p."amount" > 0
  AND NOT EXISTS (
    SELECT 1
    FROM "FinanceEntry" x
    WHERE x."orderId" = o."id"
      AND x."kind" = 'INCOME'
      AND x."deletedAt" IS NULL
  );
