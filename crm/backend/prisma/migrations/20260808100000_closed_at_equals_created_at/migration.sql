-- Дата закрытия закрытой сделки = её дата оформления.
--
-- Решение владельца: заказ считается тем месяцем, которым он ОФОРМЛЕН.
-- Новые закрытия так и проставляются (OrdersService.closingDateOf), но у
-- сделок, закрытых раньше, в базе осталась дата «когда нажали кнопку».
-- Заказ «Банофи» оформлен 28 мая, закрыт 4 августа — и его 1610 сомони
-- лежали в августовской выручке вместо майской.
--
-- Здесь эти записи приводятся к общему правилу. Заодно чинятся заказы,
-- оплаченные вовсе без даты закрытия: такие не попадали НИ В ОДИН период
-- (в аналитике для них была отдельная строка «оплачены без даты закрытия»).
--
-- Затрагиваются только закрытые этапы: у сделки в работе даты закрытия нет
-- и быть не должно. Повторный запуск ничего не меняет — правило устойчиво.
UPDATE "Order"
   SET "closedAt" = "createdAt"
 WHERE "stage" IN ('PAID', 'REJECTED')
   AND ("closedAt" IS NULL OR "closedAt" <> "createdAt");
