-- Персональный доступ к платёжным ведомостям.
--
-- Раньше галочка «без доступа к финансам» закрывала сотруднику и книгу
-- доходов компании, и ведомости разом. Но ведомость — рабочий документ
-- (бригада, объект, выплаты за смену), и владелец захотел открывать её
-- отдельным людям, не открывая им прибыль и расходы.
--
-- По умолчанию false: у тех, кому финансы и так открыты, ничего не меняется —
-- им ведомости доступны и без этой галочки.
ALTER TABLE "User" ADD COLUMN IF NOT EXISTS "canSeeReports" BOOLEAN NOT NULL DEFAULT false;
