-- Минимальная цена заказа (решение владельца, сентябрь 2026).
--
-- Маленький объект стоит фиксированно: уборка МЕНЬШЕ 50 м² — 1500 сомони,
-- от 50 м² — площадь × цена услуги, как и раньше. Порог и сумма живут в
-- карточке услуги, чтобы руководитель менял их без программиста.
--
-- Значения по умолчанию — нули: у услуги без порога правило не действует,
-- поэтому существующие строки ведут себя как прежде. Стартовые 1500/50
-- получают только услуги по площади; мойка мебели считается местами и под
-- минимум не попадает.
ALTER TABLE "Tariff" ADD COLUMN IF NOT EXISTS "minPrice" INTEGER NOT NULL DEFAULT 0;
ALTER TABLE "Tariff" ADD COLUMN IF NOT EXISTS "minArea"  INTEGER NOT NULL DEFAULT 0;

UPDATE "Tariff"
   SET "minPrice" = 1500,
       "minArea"  = 50
 WHERE "unit" = 'м²'
   AND "minPrice" = 0
   AND "minArea"  = 0;
