-- Убираем ДУБЛЬ «Химчистки мягкой мебели».
--
-- Предыдущая миграция завела услугу с ключом upholsteryDry, не зная, что
-- владелец уже добавил такую же руками через «Услуги и цены» (свой ключ).
-- В справочнике оказались две одинаковые строки.
--
-- Оставляем ЖИВУЮ запись владельца: на неё уже могут ссылаться заказы.
-- Свою удаляем совсем — она новая, в заказах её быть не может.
DELETE FROM "ExtraService"
WHERE "id" = 'upholstery_dry_seed'
  AND EXISTS (
    SELECT 1 FROM "ExtraService" e2
    WHERE e2."id" <> 'upholstery_dry_seed'
      AND e2."deletedAt" IS NULL
      AND e2."title" ILIKE '%химчистк%мебел%'
  );
