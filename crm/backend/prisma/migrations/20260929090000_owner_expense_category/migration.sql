-- Статья расхода «Расход Анисы» (просьба владельца, сентябрь 2026).
--
-- Траты владельца записывали в «Прочий расход» — и в аналитике они
-- смешивались с расходами компании. Теперь у них своя статья и своя плитка
-- «Расходы Анисы»; в «Все расходы» она не входит, из чистого дохода
-- вычитается.
--
-- ADD VALUE стоит в ОТДЕЛЬНОЙ миграции нарочно: PostgreSQL не разрешает
-- использовать новое значение перечисления в той же транзакции, где оно
-- добавлено. Существующие записи не меняются — только новый пункт в списке.
ALTER TYPE "FinanceCategory" ADD VALUE IF NOT EXISTS 'OWNER_EXPENSE';
