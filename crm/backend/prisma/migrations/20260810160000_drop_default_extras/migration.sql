-- Четыре базовые доп. услуги убраны из справочника (решение владельца).
--
-- «Мытьё окон», «Мытьё холодильника внутри», «Чистка духовки» и «Глажка
-- белья (1 час)» переносятся в корзину, а не стираются: на них ссылаются
-- уже оформленные заказы, и их история должна читаться.
--
-- Заодно снимаем пометку «Базовая» (isSystem). Пока она стояла, сервер
-- отвечал «Базовую доп. услугу удалить нельзя — её можно только скрыть»,
-- и владелец не мог убрать их сам. Без пометки он волен и удалить их, и
-- восстановить из корзины без нашего участия.
--
-- Восстанавливать их при запуске сервер больше не будет: список
-- EXTRA_DEFAULTS в tariffs.service.ts опустошён вместе с этой миграцией.
UPDATE "ExtraService"
SET "isSystem" = false,
    "isActive" = false,
    "deletedAt" = COALESCE("deletedAt", NOW()),
    "deleteReason" = COALESCE("deleteReason", 'Убрана из справочника по решению владельца')
WHERE "key" IN ('windows', 'fridge', 'oven', 'ironing');
