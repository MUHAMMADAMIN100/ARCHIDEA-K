-- Адрес клиента.
--
-- Раньше адрес жил только в заказе: у клиента без заявки его негде было
-- хранить, и при каждом новом заказе адрес спрашивали заново. Теперь он
-- спрашивается один раз при заведении клиента и подставляется в заявку.
--
-- Поле необязательное на уровне базы: у 27 уже заведённых клиентов адреса
-- нет, и требование «не пусто» сломало бы их сохранение. Обязательным его
-- делает форма нового клиента.
ALTER TABLE "Client" ADD COLUMN IF NOT EXISTS "address" TEXT;
