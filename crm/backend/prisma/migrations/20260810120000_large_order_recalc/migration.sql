-- Метка «Крупный» пересчитывается по нынешнему порогу — 5000 сомони.
--
-- Признак хранится в строке заказа и раньше проставлялся один раз, при
-- создании. Порог с тех пор менялся (было 2000), поэтому в базе остались
-- заказы с меткой «КРУПНЫЙ» на суммы вроде 2352 — и наоборот, крупные без
-- метки. Правило то же, что в коде: берём итоговую цену, а пока её нет —
-- расчётную (backend/src/orders/order-pricing.ts, LARGE_ORDER_THRESHOLD).
--
-- Трогаем только те строки, где значение расходится с правилом, чтобы не
-- переписывать без нужды всю таблицу.
UPDATE "Order"
SET "isLarge" = (COALESCE("finalPrice", "estimatedPrice", 0) >= 5000)
WHERE "isLarge" IS DISTINCT FROM (COALESCE("finalPrice", "estimatedPrice", 0) >= 5000);
