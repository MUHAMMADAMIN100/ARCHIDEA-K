-- Ибодат становится управляющей (решение владельца).
--
-- Ищем по имени и логину: учётка заведена вручную, её логин в коде проекта
-- не зафиксирован, а нынешняя роль неизвестна — «Ведомостей» у неё нет, что
-- бывает и у руководителя с закрытыми финансами, и у менеджера. Поэтому по
-- роли не отбираем вовсе, только по человеку.
--
-- Владельца компании не трогаем ни при каких совпадениях: понижение его роли
-- отняло бы у него управление доступами, и вернуть их было бы некому.
UPDATE "User"
SET "role" = 'SUPERVISOR'
WHERE "deletedAt" IS NULL
  AND "isOwner" = false
  AND ("fullName" ILIKE '%Ибодат%' OR "login" ILIKE 'ibodat%');
