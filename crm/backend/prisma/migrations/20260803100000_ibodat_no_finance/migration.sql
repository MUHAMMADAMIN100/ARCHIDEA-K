-- Персональный запрет на деньги компании для Ибодат (решение владельца).
--
-- Это данные, а не правило в коде: галочку «без доступа к финансам» в
-- карточке сотрудника владелец может снять в любой момент. Здесь она
-- проставляется один раз, чтобы запрет начал действовать сразу после
-- обновления, а не после ручного захода в карточку.
UPDATE "User"
SET "noFinance" = true
WHERE lower("login") = 'ibodat'
   OR "fullName" ILIKE 'ибодат%';
