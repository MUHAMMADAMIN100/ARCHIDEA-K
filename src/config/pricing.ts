/** Услуга: уборка по м² (3 цены по степени) или мебель (цена за место) */
export interface CleaningType {
  /*
   * Идентификатор — произвольная строка, а не тройка литералов: директор
   * заводит новые услуги в CRM, и сайт обязан их показывать. Раньше тип
   * допускал только три значения, поэтому новая услуга не могла тут появиться.
   */
  id: string;
  title: string;
  /** Цена за единицу: за м² или за место. Одна — степень на неё не влияет */
  price: number;
  /**
   * Минимальная цена и порог объёма (решение владельца): объект МЕНЬШЕ
   * minArea единиц стоит ровно minPrice, от порога — объём × цена.
   * Нет полей или нули — правила у услуги нет (мойка мебели).
   */
  minPrice?: number;
  minArea?: number;
  /** true — цена за посадочное место (мягкая мебель), не за м² */
  perSeat?: boolean;
  description: string;
  popular?: boolean;
}

